export function iconKey(id?: string, title?: string): string {
  if (id) {
    const raw = id.split(":")[0].toLowerCase();
    if (raw === "claude" || raw.includes("claude") || raw.includes("anthropic")) return "claude";
    if (raw === "codex" || raw.includes("codex") || raw.includes("openai") || raw.includes("chatgpt")) return "codex";
    if (raw === "kimi" || raw.includes("kimi") || raw.includes("moonshot")) return "kimi";
    if (raw === "grok" || raw.includes("grok") || raw.includes("xai")) return "grok";
    if (raw === "agy" || raw.includes("agy") || raw.includes("gemini") || raw.includes("antigravity")) return "agy";
    if (raw === "opencode-go" || raw.includes("opencode")) return "opencode-go";
    if (raw === "muse" || raw.includes("muse")) return "muse";
    return raw;
  }
  if (title) {
    const lower = title.toLowerCase();
    if (lower.includes("claude") || lower.includes("anthropic")) return "claude";
    if (lower.includes("codex") || lower.includes("openai") || lower.includes("chatgpt")) return "codex";
    if (lower.includes("kimi") || lower.includes("moonshot")) return "kimi";
    if (lower.includes("grok") || lower.includes("xai")) return "grok";
    if (lower.includes("gemini") || lower.includes("agy") || lower.includes("antigravity")) return "agy";
    if (lower.includes("opencode")) return "opencode-go";
    if (lower.includes("muse")) return "muse";
  }
  return "";
}

/**
 * Provider brand mark: renders the official vector logo for supported AI providers,
 * tinted with `providerTint`. Unknown ids fall back to a styled monogram letter.
 */
export function ProviderIcon({
  id,
  title,
  size = 18,
}: {
  id?: string;
  title: string;
  size?: number;
}) {
  const key = iconKey(id, title);
  const mark = LOGO_PATHS[key];
  if (!mark) {
    return (
      <span className="pmono" style={{ fontSize: Math.round(size * 0.88) }} aria-hidden="true">
        {title.trim().charAt(0).toUpperCase()}
      </span>
    );
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      fillRule="evenodd"
      aria-hidden="true"
      style={{ display: "block" }}
    >
      {mark}
    </svg>
  );
}

export function providerColorKey(id: string): string {
  if (id === "agy:3p" || id.endsWith(":3p")) return "agy-3p";
  return iconKey(id);
}

export function providerTint(id: string): React.CSSProperties {
  const is3p = id === "agy:3p" || id.endsWith(":3p");
  if (is3p) {
    return {
      background: `color-mix(in oklch, var(--p-agy-3p, var(--p-agy, var(--surface-raised))) 18%, transparent)`,
      color: `var(--p-agy-3p, var(--p-agy, var(--ink)))`,
    };
  }
  const key = iconKey(id);
  return {
    background: `color-mix(in oklch, var(--p-${key}, var(--surface-raised)) 18%, transparent)`,
    color: `var(--p-${key}, var(--ink))`,
  };
}
